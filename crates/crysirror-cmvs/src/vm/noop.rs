//! Profile-specific dispatch entries that return without side effects.
//! The PC 20160201 x64 table jumps directly to RVA 0x823e7.
//! That case returns 0x4000 without touching the result bank or stack.
//! See the case table in `tools/native-api/cmvs-20160201.json`.

/// Slots that hold a real handler in the 2021-10-07 table but return at once in 2016.
pub(super) fn implemented_in_20211007(opcode: u16) -> bool {
    matches!(
        opcode,
        0x20c4..=0x20c6
            | 0x20e4
            | 0x20e7
            | 0x20ef
            | 0x211d
            | 0x2268..=0x226e
            | 0x22ed
            | 0x22f9
            | 0x23ac
            | 0x23ae
            | 0x23b8..=0x23bb
            | 0x23c0..=0x23c2
            | 0x23c5..=0x23c7
    )
}

